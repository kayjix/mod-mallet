#[test]
fn the_profile_says_which_plugins_load_and_what_it_keeps_for_itself() {
    let dir = portable_instance();
    let setup = read(dir.path());
    let profile = setup.profile();
    assert_eq!(profile.name, "Default");
    assert_eq!(profile.dir, dir.path().join("profiles").join("Default"));
    assert_eq!(
        profile.plugins,
        [PluginEntry {
            name: "Patch Hub.esp".to_owned(),
            active: true
        }]
    );
    assert_eq!(profile.load_order, ["Skyrim.esm", "Patch Hub.esp"]);
    assert!(profile.settings.local_saves && profile.settings.local_settings);
    assert_eq!(setup.settings().game_id(), Some("skyrimse"));
}

/// A global instance: its settings in the local application data, its mods
/// and profiles in a base folder elsewhere, and a profile that is not the
/// one in use.
#[test]
fn a_global_instance_with_its_folders_elsewhere_is_read() {
    let local = tempfile::tempdir().unwrap();
    let base = tempfile::tempdir().unwrap();
    let instance_dir = instance::global_instances_dir(local.path()).join("Fallout");
    let base_text = base.path().to_string_lossy().replace('\\', "\\\\");
    write(
        &instance_dir,
        "ModOrganizer.ini",
        &format!(
            "[General]\r\ngameName=Fallout 4\r\nselected_profile=@ByteArray(Main)\r\n\r\n[Settings]\r\nbase_directory=@ByteArray({base_text})\r\nmod_directory=%BASE_DIR%/staging\r\n"
        ),
    );
    write(base.path(), "profiles/Main/modlist.txt", "+Armour\r\n");
    write(
        base.path(),
        "profiles/Survival/modlist.txt",
        "+Weapons\r\n-Armour\r\n",
    );
    write(base.path(), "staging/Armour/meshes/armour.nif", "nif");
    write(base.path(), "staging/Weapons/meshes/gun.nif", "nif");

    let [instance] = global_instances(local.path()).try_into().unwrap();
    assert!(!instance.portable);
    assert_eq!(instance.name, "Fallout");

    let main = Mo2Setup::read(&instance, None).unwrap();
    assert_eq!(main.settings().game_id(), Some("fallout4"));
    assert_eq!(
        provider(&main, "data/meshes/armour.nif").as_deref(),
        Some("Armour")
    );
    assert_eq!(provider(&main, "data/meshes/gun.nif"), None);

    let survival = Mo2Setup::read(&instance, Some("Survival")).unwrap();
    assert_eq!(
        provider(&survival, "data/meshes/gun.nif").as_deref(),
        Some("Weapons")
    );
    assert_eq!(provider(&survival, "data/meshes/armour.nif"), None);
    // Without an overwrite folder nothing is in it.
    assert_eq!(
        survival.staged_files(&survival.mod_ref(OVERWRITE_ID)),
        Some(Vec::new())
    );
}

#[test]
