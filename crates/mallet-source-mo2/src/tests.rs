#[test]
fn a_mod_without_a_folder_has_no_files_and_the_rest_is_read() {
    let dir = portable_instance();
    write(
        dir.path(),
        "profiles/Default/modlist.txt",
        "+Gone\r\n+Patch Hub\r\n+Patch Hub\r\n",
    );
    let setup = read(dir.path());
    assert_eq!(setup.staged_files(&setup.mod_ref("Gone")), Some(Vec::new()));
    assert_eq!(
        provider(&setup, "data/patch hub.esp").as_deref(),
        Some("Patch Hub")
    );
    // A mod listed twice is one mod.
    assert_eq!(setup.mods().len(), 2);
}

#[test]
fn nothing_is_written_while_reading() {
    let dir = portable_instance();
    let before = snapshot(dir.path());
    let _ = read(dir.path());
    assert_eq!(snapshot(dir.path()), before);
}

/// Every file below `root` with its size and modification time.
fn snapshot(root: &Path) -> Vec<(String, u64, std::time::SystemTime)> {
    let mut found = Vec::new();
    let mut pending = vec![root.to_path_buf()];
    while let Some(dir) = pending.pop() {
        for entry in std::fs::read_dir(dir).unwrap().flatten() {
            let meta = entry.metadata().unwrap();
            if meta.is_dir() {
                pending.push(entry.path());
            } else {
                found.push((
                    entry.path().display().to_string(),
                    meta.len(),
                    meta.modified().unwrap(),
                ));
            }
        }
    }
    found.sort();
    found
}

proptest! {
    #[test]
    fn never_panics_on_arbitrary_lists(modlist in ".*", files in proptest::collection::vec(".*", 0..8)) {
        let entries = profile::parse_modlist(&modlist);
        let all: HashMap<String, Vec<String>> = entries
            .iter()
            .map(|entry| (entry.name.clone(), files.clone()))
            .collect();
        let setup = Mo2Setup::new(
            InstanceSettings::default(),
            Mo2Profile::default(),
            &entries,
            &HashMap::new(),
            &all,
            &files,
        );
        for file in &files {
            let path = GamePath::new("data").join(file);
            let _ = setup.provider_of(&path);
            let _ = setup.switched_off_with(&path);
        }
        let _ = setup.data_folders();
    }
}
