//! End-to-end tests of a scan of a setup that Mod Organizer 2 manages
//! (ADR 0064), against a made-up game directory and a made-up portable
//! instance. Every file is synthetic (ADR 0017).

// Helper functions of an integration test are not inside a `#[test]`
// function, so the test exemptions in clippy.toml do not reach them.
#![allow(clippy::unwrap_used, clippy::indexing_slicing, clippy::panic)]

use std::fs;
use std::path::{Path, PathBuf};

use mallet_core::{
    Action, ActionStatus, ArgValue, LocationOrigin, LocationRole, ModRef, ScanReport, Severity,
};
use mallet_engine::{ManagerOptions, ModManager, ScanOptions, Settings, planned_locations, scan};
use mallet_formats_bethesda::fixture;

const MASTER_FLAG: u32 = 1;

/// A game directory with nothing but the game's master file, and beside it
/// a portable Mod Organizer instance that keeps every mod in its folder.
struct Mo2Setup {
    root: tempfile::TempDir,
}

impl Mo2Setup {
    /// The reference problem of milestone 1, the Mod Organizer way: Grass
    /// Mod packs a fern in its archive, Flora Mod brings it loose and has
    /// the higher priority. An older flora mod is switched off, a separator
    /// stands between them, and a tool wrote a file into the overwrite
    /// folder.
    fn new() -> Self {
        let setup = Self {
            root: tempfile::tempdir().unwrap(),
        };
        setup.write(
            "Game/Data/Skyrim.esm",
            &fixture::plugin(&[], MASTER_FLAG, &[]),
        );
        let mo2 = "MO2";
        setup.write(&format!("{mo2}/ModOrganizer.exe"), b"");
        setup.write(&format!("{mo2}/portable.txt"), b"");
        setup.write(
            &format!("{mo2}/ModOrganizer.ini"),
            b"[General]\r\ngameName=Skyrim Special Edition\r\nselected_profile=@ByteArray(Default)\r\n",
        );
        setup.write(
            &format!("{mo2}/profiles/Default/modlist.txt"),
            b"# This file was automatically generated by Mod Organizer.\r\n+Flora Mod\r\n-Old Flora\r\n+Landscape_separator\r\n+Grass Mod\r\n*DLC: Dawnguard\r\n",
        );
        setup.write(
            &format!("{mo2}/profiles/Default/plugins.txt"),
            b"# This file was automatically generated by Mod Organizer.\r\n*Grass.esp\r\n",
        );
        setup.write(
            &format!("{mo2}/profiles/Default/loadorder.txt"),
            b"Skyrim.esm\r\nGrass.esp\r\n",
        );
        let plugin = fixture::plugin(&["Skyrim.esm"], 0, &[]);
        setup.write(&format!("{mo2}/mods/Grass Mod/Grass.esp"), &plugin);
        setup.write(
            &format!("{mo2}/mods/Grass Mod/Grass.bsa"),
            &fixture::bsa(&[
                r"meshes\landscape\grass\fern.nif",
                r"textures\landscape\grass\fern.dds",
                r"textures\landscape\grass\moss.dds",
            ]),
        );
        setup.write(
            &format!("{mo2}/mods/Grass Mod/meta.ini"),
            b"[General]\r\ngameName=SkyrimSE\r\nmodid=1234\r\nversion=1.0\r\nnewestVersion=1.1\r\n",
        );
        setup.write(
            &format!("{mo2}/mods/Flora Mod/meshes/landscape/grass/fern.nif"),
            b"mesh",
        );
        setup.write(
            &format!("{mo2}/mods/Flora Mod/textures/landscape/grass/fern.dds"),
            b"texture",
        );
        setup.write(
            &format!("{mo2}/mods/Old Flora/textures/landscape/grass/moss.dds"),
            b"old",
        );
        setup.write(&format!("{mo2}/overwrite/tool/output.txt"), b"tool");
        setup
    }

    fn write(&self, relative: &str, content: &[u8]) {
        let path = self.root.path().join(relative);
        fs::create_dir_all(path.parent().unwrap()).unwrap();
        fs::write(path, content).unwrap();
    }

    fn instance(&self) -> PathBuf {
        self.root.path().join("MO2")
    }

    fn options(&self) -> ScanOptions {
        ScanOptions {
            game_dir: Some(self.root.path().join("Game")),
            // Tests never look at the real logs, LOOT or Vortex of the
            // machine they run on.
            extender_log: Some(self.root.path().join("none").join("skse64.log")),
            masterlist: Some(self.root.path().join("none").join("masterlist.yaml")),
            manager_state: Some(self.root.path().join("none").join("state.json")),
            manager: ModManager::ModOrganizer {
                instance: Some(self.instance()),
                profile: None,
            },
            ..ScanOptions::default()
        }
    }
}

fn only<'a>(report: &'a ScanReport, kind: &str) -> &'a mallet_core::Finding {
    let found: Vec<_> = report.findings.iter().filter(|f| f.kind == kind).collect();
    assert_eq!(found.len(), 1, "{kind}: {:#?}", report.findings);
    found[0]
}

#[test]
fn loose_files_of_a_mod_over_another_mods_archive_are_found_as_with_vortex() {
    let setup = Mo2Setup::new();
    let report = scan(&setup.options()).unwrap();

    assert_eq!(report.plugins_checked, 2);
    assert_eq!(report.archives_checked, 1);
    let finding = only(&report, "assets.loose-over-archive");
    assert_eq!(finding.severity, Severity::Info);
    assert_eq!(finding.args["count"], ArgValue::Number(2));
    assert_eq!(finding.args["winnerMod"], ArgValue::from("Flora Mod"));
    assert_eq!(finding.args["archive"], ArgValue::from("grass.bsa"));
    assert_eq!(finding.args["archiveMod"], ArgValue::from("Grass Mod"));
    assert_eq!(report.manager.as_deref(), Some("mo2"));
}

#[test]
fn the_mods_come_with_their_state_and_details() {
    let setup = Mo2Setup::new();
    let report = scan(&setup.options()).unwrap();

    let names: Vec<_> = report
        .mods
        .iter()
        .map(|m| m.mod_ref.name.as_str())
        .collect();
    assert_eq!(names, ["Grass Mod", "Old Flora", "Flora Mod"]);
    let grass = &report.mods[0];
    assert_eq!(grass.mod_ref.source, "mo2");
    assert!(grass.enabled);
    assert_eq!(grass.version.as_deref(), Some("1.0"));
    assert_eq!(grass.newer_version.as_deref(), Some("1.1"));
    assert_eq!(
        grass.page.as_deref(),
        Some("https://www.nexusmods.com/skyrimspecialedition/mods/1234")
    );
    assert!(!report.mods[1].enabled);
}

#[test]
fn the_report_names_mod_organizers_places() {
    let setup = Mo2Setup::new();
    let report = scan(&setup.options()).unwrap();
    let place = |role: LocationRole| {
        report
            .locations
            .iter()
            .find(|location| location.role == role)
            .unwrap_or_else(|| panic!("{role:?}: {:#?}", report.locations))
    };

    let instance = place(LocationRole::ManagerInstance);
    assert!(instance.found);
    assert_eq!(instance.origin, LocationOrigin::Given);
    let plugins = place(LocationRole::PluginList);
    assert!(plugins.found);
    assert_eq!(plugins.origin, LocationOrigin::ManagerSettings);
    assert!(Path::new(&plugins.path).starts_with(setup.instance().join("profiles")));
    assert!(place(LocationRole::ManagerMods).found);
    // Vortex's places are not read.
    assert!(
        report
            .locations
            .iter()
            .all(|location| location.role != LocationRole::DeploymentManifest)
    );
}

#[test]
fn an_instance_that_is_not_there_leaves_the_files_without_mods() {
    let setup = Mo2Setup::new();
    let options = ScanOptions {
        manager: ModManager::ModOrganizer {
            instance: Some(setup.root.path().join("nowhere")),
            profile: None,
        },
        ..setup.options()
    };
    let report = scan(&options).unwrap();
    assert_eq!(report.mods, [] as [mallet_core::ModInfo; 0]);
    let instance = report
        .locations
        .iter()
        .find(|location| location.role == LocationRole::ManagerInstance)
        .unwrap();
    assert!(!instance.found);
}

#[test]
fn an_instance_of_another_game_is_not_used() {
    let setup = Mo2Setup::new();
    setup.write(
        "MO2/ModOrganizer.ini",
        b"[General]\r\ngameName=Fallout 4\r\n",
    );
    // Without the instance's profile the list of active plugins is looked
    // for elsewhere; never in the machine's own folders.
    let options = ScanOptions {
        local_dir: Some(setup.root.path().join("none")),
        ..setup.options()
    };
    let report = scan(&options).unwrap();
    assert_eq!(report.mods, [] as [mallet_core::ModInfo; 0]);
    // Without the mods' folders, the mods' plugin is not in the game.
    assert_eq!(report.plugins_checked, 1);
}

#[test]
fn a_scan_writes_nothing_into_the_instance() {
    let setup = Mo2Setup::new();
    let before = snapshot(&setup.instance());
    scan(&setup.options()).unwrap();
    assert_eq!(snapshot(&setup.instance()), before);
}

#[test]
fn the_places_page_shows_the_instance_and_not_vortex() {
    let setup = Mo2Setup::new();
    let planned = planned_locations(&setup.options());
    let roles: Vec<_> = planned.iter().map(|location| location.role).collect();
    assert!(roles.contains(&LocationRole::ManagerInstance), "{roles:?}");
    assert!(
        !roles.contains(&LocationRole::DeploymentManifest),
        "{roles:?}"
    );
    assert!(!roles.contains(&LocationRole::ManagerState), "{roles:?}");
    let instance = planned
        .iter()
        .find(|location| location.role == LocationRole::ManagerInstance)
        .unwrap();
    assert!(instance.found);
}

#[test]
fn the_chosen_manager_is_kept_per_game_and_used_for_scans_and_actions() {
    let setup = Mo2Setup::new();
    let settings = Settings {
        game: "skyrimse".to_owned(),
        ..Settings::default()
    }
    .with_manager("mo2", Some(setup.instance()));
    assert_eq!(settings.manager(), "mo2");
    assert_eq!(
        settings.scan_options().manager,
        ModManager::ModOrganizer {
            instance: Some(setup.instance()),
            profile: None,
        }
    );
    assert!(settings.manager_options().by_hand);
    let choice = settings.managers();
    assert_eq!(choice.active, "mo2");
    assert!(choice.chosen);
    let mo2 = choice.managers.iter().find(|m| m.id == "mo2").unwrap();
    assert!(mo2.found);
    assert!(!mo2.link);
    assert!(mo2.instances.iter().any(|i| i.portable && i.name == "MO2"));

    // Back to Vortex: the instance is no longer named.
    let vortex = settings.with_manager("vortex", None);
    assert_eq!(vortex.manager(), "vortex");
    assert_eq!(vortex.scan_options().manager, ModManager::Vortex);
    assert!(!vortex.manager_options().by_hand);
    // An unknown manager changes nothing.
    assert_eq!(
        settings.with_manager("kortex", Some(setup.instance())),
        settings
    );
}

#[test]
fn actions_are_left_to_the_user_and_nothing_is_written_into_the_instance() {
    let setup = Mo2Setup::new();
    let before = snapshot(&setup.instance());
    let options = ManagerOptions {
        game: Some("skyrimse".to_owned()),
        link_dir: Some(setup.root.path().join("bridge")),
        by_hand: true,
        ..ManagerOptions::default()
    };
    let flora = ModRef {
        source: "mo2".to_owned(),
        id: "Flora Mod".to_owned(),
        name: "Flora Mod".to_owned(),
    };
    for action in [
        Action::DisableMod {
            mod_ref: flora.clone(),
        },
        Action::EnableMod {
            mod_ref: flora.clone(),
        },
        Action::ReinstallMod {
            mod_ref: flora,
            tick: Vec::new(),
        },
        Action::LoadAfter {
            plugin: "Grass.esp".to_owned(),
            after: "Skyrim.esm".to_owned(),
        },
    ] {
        let outcome = mallet_engine::run_action(&action, &options);
        assert_eq!(outcome.status, ActionStatus::ByHand, "{action:?}");
    }
    assert_eq!(snapshot(&setup.instance()), before);
    // Nothing was handed to a link either.
    assert!(!setup.root.path().join("bridge").join("requests").exists());
}

/// Every file below `root` with its size and modification time.
fn snapshot(root: &Path) -> Vec<(PathBuf, u64, std::time::SystemTime)> {
    let mut found = Vec::new();
    let mut pending = vec![root.to_path_buf()];
    while let Some(dir) = pending.pop() {
        for entry in fs::read_dir(dir).unwrap().flatten() {
            let meta = entry.metadata().unwrap();
            if meta.is_dir() {
                pending.push(entry.path());
            } else {
                found.push((entry.path(), meta.len(), meta.modified().unwrap()));
            }
        }
    }
    found.sort();
    found
}
